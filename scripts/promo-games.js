// Promo games (spin to win): pure definitions and draw logic (unit-tested; no network here).
//
// Three collections:
//   1. `promoGames` — one row per game (name, status).
//   2. `promoGameItems` — the wheel segments: label, kind (win / noWin), probability weight,
//      number of win items available (winLimit, 0 = unlimited), optional linked coupon, color.
//   3. `promoGameSpins` — one row per spin: game, item landed on, customer, when, won or not.
//
// Draw rules (eligibleItems + pickWeighted below):
//   - A segment's chance is weight / total weight of the eligible segments.
//   - A "win" segment whose recorded wins have reached its winLimit is excluded from the draw
//     (its remaining probability is redistributed over the remaining segments).
//   - "noWin" segments (e.g. "Try again") are always eligible.
//
// The Promo Games tab on the Messages page (scripts/ui/promo-games-tab.js) manages games and
// runs the animated wheel. Applied by scripts/apply-promo-games.js.

const GAMES_COLLECTION = 'promoGames';
const ITEMS_COLLECTION = 'promoGameItems';
const SPINS_COLLECTION = 'promoGameSpins';
const PROMO_TAB_TITLE = 'Promo Games';

const SEGMENT_COLORS = ['#d4621c', '#0e7490', '#6d28d9', '#be185d', '#15803d', '#b45309', '#1d4ed8', '#b91c1c', '#0f766e', '#7c3aed'];

// Segments that can still be landed on: positive weight, and win segments under their limit.
function eligibleItems(items, winCountByItemId = {}) {
  return (items || []).filter((item) => {
    if (!item || !(Number(item.weight) > 0)) return false;
    if (item.kind === 'noWin') return true;
    const limit = Number(item.winLimit) || 0;
    if (!limit) return true;
    return (winCountByItemId[item.id] || 0) < limit;
  });
}

// Weighted random pick over the given items. Returns the picked item or null.
function pickWeighted(items, random = Math.random) {
  const pool = (items || []).filter((i) => Number(i.weight) > 0);
  const total = pool.reduce((sum, i) => sum + Number(i.weight), 0);
  if (!total) return null;
  let roll = random() * total;
  for (const item of pool) {
    roll -= Number(item.weight);
    if (roll < 0) return item;
  }
  return pool[pool.length - 1];
}

// Display probabilities: id -> percent (one decimal), over the given items.
function probabilities(items) {
  const pool = (items || []).filter((i) => Number(i.weight) > 0);
  const total = pool.reduce((sum, i) => sum + Number(i.weight), 0);
  const out = {};
  for (const item of pool) out[item.id] = total ? Math.round((Number(item.weight) / total) * 1000) / 10 : 0;
  return out;
}

